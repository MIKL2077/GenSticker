def _values(value):
    if isinstance(value, str):
        return [value]
    return [v for v in value or () if isinstance(v, str)] if isinstance(value, (list, tuple, set)) else []


def _match(text, signal):
    if signal.isascii():
        return re.search(r'(?<![a-z0-9])' + re.escape(signal) + r'(?![a-z0-9])', text) is not None
    return signal in text


def keywords(metadata, originals=()):
    name = str(metadata.get('name') or '')
    captions = _values(metadata.get('default_texts'))
    original = _values(originals)
    stored = _values(metadata.get('keywords'))
    base = [name, *original, *stored, *captions]
    tags = [v for v in _values(metadata.get('tags')) if v.lower() not in
            {'general','happy','angry','sad','surprised','face','image','text','mixed'}]
    category = re.sub(r'^\d+[A-Za-z_]*|BQB', ' ', str(metadata.get('category') or ''))
    original_evidence = [word for word in original if word not in stored]
    evidence = unicodedata.normalize('NFKC', ' '.join([name, *original_evidence, *captions, *tags, category])).lower()
    if '熊猫' in evidence and '猫' not in evidence.replace('熊猫','') and not _match(evidence,'cat'):
        cat_aliases = set(next(words.split() for words,_ in GROUPS if words.startswith('猫咪')))
        base = [word for word in base if word.lower() not in cat_aliases]
    aliases = []
    for words, signals in GROUPS:
        if any(v in evidence for v in NEGATIONS.get(words.split()[0], ())):
            continue
        text = evidence.replace('熊猫', '') if words.startswith('猫咪') else evidence
        if any(_match(text, signal) for signal in signals):
            aliases.extend(words.split())
    categories = re.findall(r'[a-zA-Z]{2,}|[\u4e00-\u9fff]{2,20}', category)
    output, seen = [], set()
    for value in [*base, *aliases, *TITLE_ALIASES.get(name,'').split(), *tags, *categories]:
        value = unicodedata.normalize('NFKC', value).strip()[:80]
        if value and value.casefold() not in seen:
            seen.add(value.casefold())
            output.append(value)
        if len(output) >= 128:
            break
    return output
